import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

import numpy as np
from src.phase2.hac import scalar_hac_prewhitened

# ---------------------------------------------------------------------------
# Pre-computed R reference values (Strategy B fallback).
# Fill these from the R script in the module docstring before empirical run.
# Leave as empty list / None to trigger SKIP.
# ---------------------------------------------------------------------------

# The arima.sim series: set.seed(20260923); u <- arima.sim(list(ar=0.5), 100, sd=1)
# paste(round(as.numeric(u), 10), collapse=", ")
REF_SERIES: list[float] = []   # <— fill from R before empirical run

# sandwich::lrvar(u, type="Andrews", prewhite=TRUE, adjust=FALSE) on above series
REF_LRV: float | None = None   # <— fill from R before empirical run

# ---------------------------------------------------------------------------
# Tolerance: 4 significant figures
# ---------------------------------------------------------------------------
RTOL_4SIG = 5e-4   # relative tolerance for 4 significant figures


def run_strategy_a_rpy2() -> tuple[bool, str]:
    """
    Strategy A: generate arima.sim series via rpy2, compute lrvar in R,
    compare to scalar_hac_prewhitened on the same series.

    Returns
    -------
    (passed, message)
    """
    try:
        import rpy2.robjects as ro
        from rpy2.robjects import numpy2ri
        numpy2ri.activate()
        importr = __import__('rpy2.robjects.packages', fromlist=['importr']).importr
    except ImportError:
        return None, "rpy2 not available"

    try:
        sandwich = importr("sandwich")
    except Exception as e:
        return None, f"R sandwich package not available: {e}"

    try:
        # Generate series in R
        ro.r("set.seed(20260923)")
        ro.r("u_r <- arima.sim(model=list(ar=0.5), n=100, sd=1)")

        # R reference value
        ro.r("ref_r <- sandwich::lrvar(u_r, type='Andrews', prewhite=TRUE, adjust=FALSE)")
        ref_r = float(ro.r("ref_r")[0])

        # Extract series for Python
        u_r_arr = np.array(ro.r("as.numeric(u_r)"))
        numpy2ri.deactivate()

        # Python computation on same series
        py_val = scalar_hac_prewhitened(u_r_arr)

        rel_diff = abs(py_val - ref_r) / abs(ref_r) if abs(ref_r) > 1e-15 else abs(py_val)
        passed = rel_diff < RTOL_4SIG
        msg = (
            f"R sandwich lrvar = {ref_r:.8f}\n"
            f"  Python scalar_hac_prewhitened = {py_val:.8f}\n"
            f"  Relative difference = {rel_diff:.2e} "
            f"({'PASS' if passed else 'FAIL'} at rtol={RTOL_4SIG:.1e})"
        )
        return passed, msg

    except Exception as e:
        return None, f"rpy2 execution error: {e}"


def run_strategy_b_hardcoded() -> tuple[bool | None, str]:
    """
    Strategy B: compare against hard-coded R reference series and lrvar value.

    Returns
    -------
    (passed, message)  — passed=None means SKIP (constants not filled)
    """
    if len(REF_SERIES) == 0 or REF_LRV is None:
        return None, (
            "REF_SERIES and/or REF_LRV not filled. "
            "Run the R script in this file's docstring and populate the constants "
            "before empirical execution. This is a PRE-EXECUTION OBLIGATION."
        )

    u_hard = np.array(REF_SERIES, dtype=float)
    if len(u_hard) != 100:
        return False, f"REF_SERIES has {len(u_hard)} elements; expected 100."

    py_val = scalar_hac_prewhitened(u_hard)
    ref_r = REF_LRV
    rel_diff = abs(py_val - ref_r) / abs(ref_r) if abs(ref_r) > 1e-15 else abs(py_val)
    passed = rel_diff < RTOL_4SIG
    msg = (
        f"R sandwich lrvar (hardcoded) = {ref_r:.8f}\n"
        f"  Python scalar_hac_prewhitened = {py_val:.8f}\n"
        f"  Relative difference = {rel_diff:.2e} "
        f"({'PASS' if passed else 'FAIL'} at rtol={RTOL_4SIG:.1e})"
    )
    return passed, msg


def main() -> int:
    """
    Run the HAC R sandwich known-answer gate.

    Returns 0 on pass, 1 on fail, 2 on skip.
    """
    print("=== H1 HAC known-answer gate: R sandwich 4-significant-figure comparison ===")

    # Try Strategy A first (live rpy2)
    passed_a, msg_a = run_strategy_a_rpy2()
    if passed_a is not None:
        print(f"Strategy A (live rpy2):")
        print(f"  {msg_a}")
        if passed_a:
            print("\nH1 HAC GATE: PASS  (rpy2 live comparison)")
            return 0
        else:
            print("\nH1 HAC GATE: FAIL  (rpy2 live comparison)")
            return 1
    else:
        print(f"Strategy A skipped: {msg_a}")

    # Fall through to Strategy B
    passed_b, msg_b = run_strategy_b_hardcoded()
    if passed_b is None:
        print(f"Strategy B (hardcoded):")
        print(f"  SKIP: {msg_b}")
        print("\nH1 HAC GATE: SKIP — pre-execution obligation not yet satisfied.")
        print("  This gate MUST pass before empirical run. Fill REF_SERIES and REF_LRV.")
        return 2
    else:
        print(f"Strategy B (hardcoded):")
        print(f"  {msg_b}")
        if passed_b:
            print("\nH1 HAC GATE: PASS  (hardcoded reference)")
            return 0
        else:
            print("\nH1 HAC GATE: FAIL  (hardcoded reference — check implementation)")
            return 1


if __name__ == "__main__":
    rc = main()
    # Exit 0 (pass) or 2 (skip) are both acceptable at harness-build time.
    # Exit 1 (fail) means the implementation disagrees with R — must resolve.
    if rc == 1:
        sys.exit(1)
    # rc=2 (SKIP): harness built; pre-execution obligation remains.
    sys.exit(0)
